import json
import torch
from typing import List
from benchmark.scenarios.base import Scenario, ProblemInstance, Agent, Task

class RealGitHubScenario(Scenario):
    """
    Scenario that loads real-world GitHub issues and Agent profiles 
    from a processed dataset file generated by dataset_pipeline.
    """
    def __init__(self, dataset_path: str = "dataset_pipeline/processed_gh_dataset.json"):
        self.dataset_path = dataset_path
        self.data = None
        self._load_dataset()

    def _load_dataset(self):
        with open(self.dataset_path, "r", encoding="utf-8") as f:
            self.data = json.load(f)

    def generate(self, seed: int) -> ProblemInstance:
        # Load agents
        agents = []
        for a_data in self.data["agents"]:
            agents.append(
                Agent(
                    id=a_data["id"],
                    role=a_data["role"],
                    capability_embedding=torch.tensor(a_data["capability_embedding"], dtype=torch.float32),
                    tags=a_data.get("tags", [])
                )
            )

        # Load tasks
        tasks = []
        for t_data in self.data["tasks"]:
            tasks.append(
                Task(
                    id=t_data["id"],
                    embedding=torch.tensor(t_data["embedding"], dtype=torch.float32),
                    tags=t_data.get("labels", [])
                )
            )

        # Load matrices
        Theta = torch.tensor(self.data["interaction_graph"], dtype=torch.float32)
        C = torch.tensor(self.data["co_assignment_costs"], dtype=torch.float32)
        W_risk = torch.tensor(self.data["risk_weights"], dtype=torch.float32)

        return ProblemInstance(
            agents=agents,
            tasks=tasks,
            interaction_graph=Theta,
            co_assignment_costs=C,
            risk_weights=W_risk
        )
